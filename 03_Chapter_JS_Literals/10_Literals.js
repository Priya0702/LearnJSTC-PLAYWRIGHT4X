//JavaScript Numeric Literal
let a = 10;
console.log(a);

// let – Keyword used to declare a variable.
// a – Identifier (variable name).
// = – Assignment operator.
// 10 – Numeric Literal (a fixed numeric value written directly in the code).
// ; – Semicolon used to terminate the statement.

// What is a Literal?

// A literal is a value written directly in the source code.

// Examples:

// let age = 25;           // Number Literal
// let name = "Rahul";     // String Literal
// let isPassed = true;    // Boolean Literal
// let result = null;      // Null Literal


// Key Point: a is an identifier, while 10 is a numeric literal.