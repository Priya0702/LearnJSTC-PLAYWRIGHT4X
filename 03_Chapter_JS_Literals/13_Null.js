//JavaScript Literals: null and undefined
let no_audi= null;
let u;
console.log(no_audi);
console.log(u);


// Explanation:

// let – Keyword used to declare a variable.
// no_audi – Identifier (variable name).
// null – Represents the intentional absence of a value.
// ; – Semicolon used to terminate the statement.
// u – Identifier (variable name). It is declared but has not been assigned a value.

// Key Difference:

// null – The variable is explicitly assigned an empty or absent value.
// undefined – A declared variable that has not been assigned a value has the value undefined by default.

// Example:

// console.log(no_audi); // null
// console.log(u);                      // undefined


// Key Point: null is explicitly assigned, whereas undefined is the default value of a declared but uninitialized variable.