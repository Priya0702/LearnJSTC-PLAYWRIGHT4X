let count = 42;       // Positive integer literal
let negative = -100;  // Negative number literal
let zero = 0;         // Zero is also a numeric literal

let h = 0xFF;         // Hexadecimal literal (base 16), equal to 255
console.log(typeof h); // Output: "number" (typeof returns the data type)

let color_hex = 0xFF0000; // Hexadecimal literal representing the color red (RGB)

let octal = 0o77;     // Octal literal (base 8), equal to 63
let million = 1e6;    // Exponential notation: 1 × 10^6 = 1,000,000
let tiny = 1.5e-4;    // Exponential notation: 1.5 × 10^-4 = 0.00015

// 0x → Hexadecimal

// 0o → Octal

// 0b → Binary

// 42, 100, 500 → Normal Decimal numbers